// Generates fresh demo passwords for the two Loomline admin accounts.
//
//  - Writes ONLY salted PBKDF2-SHA256 hashes to src/app/core/auth/credentials.config.ts
//  - Writes the plaintext passwords to ../CREDENTIALS.md (git-ignored)
//
// Usage:  npm run hash-passwords
import { pbkdf2Sync, randomBytes, randomInt } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ITERATIONS = 310000;
const LENGTH = 14;
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%*-_+=?';

function password() {
  let out = '';
  for (let i = 0; i < LENGTH; i++) out += ALPHABET[randomInt(ALPHABET.length)];
  // guarantee at least one of each class
  if (!/[A-Z]/.test(out) || !/[a-z]/.test(out) || !/\d/.test(out) || !/[^A-Za-z0-9]/.test(out)) {
    return password();
  }
  return out;
}

const accounts = [
  { username: 'admin', role: 'admin' },
  { username: 'viewer', role: 'viewer' },
].map((a) => {
  const pw = password();
  const salt = randomBytes(16);
  const hash = pbkdf2Sync(pw, salt, ITERATIONS, 32, 'sha256');
  return { ...a, pw, salt: salt.toString('base64'), hash: hash.toString('base64') };
});

const ts = `// AUTO-GENERATED by scripts/gen-credentials.mjs — do not edit by hand.
// Only salted PBKDF2-SHA256 hashes are stored here; plaintext passwords live in
// the git-ignored CREDENTIALS.md. This is a demo access gate, not real security:
// everything shipped to the browser can be inspected.
import { DemoAccount } from './auth.models';

export const PBKDF2_ITERATIONS = ${ITERATIONS};

export const DEMO_ACCOUNTS: readonly DemoAccount[] = [
${accounts
  .map(
    (a) =>
      `  { username: '${a.username}', role: '${a.role}', salt: '${a.salt}', hash: '${a.hash}' },`,
  )
  .join('\n')}
];
`;
writeFileSync(resolve(here, '../src/app/core/auth/credentials.config.ts'), ts);

const md = `# Loomline admin — demo credentials

> Git-ignored. Regenerate with \`npm run hash-passwords\` inside \`frontend/\`
> (this rewrites both this file and \`src/app/core/auth/credentials.config.ts\`).

Admin area: \`/admin/login\`

| Username | Password | Role |
|---|---|---|
${accounts.map((a) => `| \`${a.username}\` | \`${a.pw}\` | ${a.role === 'admin' ? 'admin — full access' : 'viewer — read-only'} |`).join('\n')}

Hashing: PBKDF2-SHA256, ${ITERATIONS} iterations, 16-byte random salt per account.
`;
writeFileSync(resolve(here, '../../CREDENTIALS.md'), md);
console.log('Credentials regenerated.');
